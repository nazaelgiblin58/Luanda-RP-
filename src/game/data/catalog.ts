export function normalizeWeatherType(raw?: string | null): 'ensolarado' | 'nublado' | 'cacimbo' | 'chuva' | 'calor_extremo' | 'pordosol' | 'noite' {
  const s = String(raw || '').toLowerCase().trim();
  if (s === 'chuva' || s === 'chuva_tropical' || s === 'trovoada') return 'chuva';
  if (s === 'nublado' || s === 'nuvens' || s === 'encoberto') return 'nublado';
  if (s === 'calor_extremo' || s === 'calor' || s === 'onda_calor') return 'calor_extremo';
  if (s === 'cacimbo' || s === 'neblina' || s === 'nevoeiro') return 'cacimbo';
  if (s === 'pordosol' || s === 'por_do_sol' || s === 'sunset') return 'pordosol';
  if (s === 'noite' || s === 'night') return 'noite';
  return 'ensolarado';
}

